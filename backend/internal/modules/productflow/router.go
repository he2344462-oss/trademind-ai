package productflow

import "github.com/gin-gonic/gin"

func Register(g *gin.RouterGroup, h *Handler) {
	if g == nil || h == nil {
		return
	}
	g.GET("/source-products", h.ListSources)
	g.POST("/source-products", h.CreateSource)
	g.POST("/source-products/import", h.ImportSources)
	g.GET("/source-products/:id", h.GetSource)
	g.POST("/source-products/:id/candidate", h.CreateCandidate)
	g.GET("/candidates", h.ListCandidates)
	g.GET("/candidates/:id", h.GetCandidate)
	g.POST("/candidates/:id/analyze", h.AnalyzeCandidate)
	g.POST("/candidates/analyze-batch", h.CreateAnalysisBatch)
	g.POST("/candidates/bulk/:action", h.BulkCandidateAction)
	g.GET("/candidate-analysis-batches/:id", h.GetAnalysisBatch)
	g.GET("/candidate-analysis-batches", h.ListAnalysisBatches)
	g.GET("/candidate-analysis-batches/:id/items", h.ListAnalysisBatchItems)
	g.POST("/candidate-analysis-batches/:id/pause", h.PauseAnalysisBatch)
	g.POST("/candidate-analysis-batches/:id/resume", h.ResumeAnalysisBatch)
	g.POST("/candidate-analysis-batches/:id/cancel", h.CancelAnalysisBatch)
	g.POST("/candidate-analysis-batches/:id/retry-failed", h.RetryFailedAnalysisBatch)
	g.GET("/candidate-analysis-batches/:id/top", h.TopRecommendations)
	g.POST("/candidates/:id/market-signals", h.CreateMarketSignal)
	g.GET("/candidates/:id/market-signals", h.ListMarketSignals)
	g.POST("/market-signals/import", h.ImportMarketSignals)
	g.POST("/imports/market-signals/preview", h.PreviewMarketSignalCSV)
	g.POST("/imports/market-signals/confirm", h.ConfirmMarketSignalCSV)
	g.GET("/market-signal-providers/status", h.MarketSignalProviderStatuses)
	g.GET("/market-signal-provider-configs", h.ListMarketProviderConfigs)
	g.POST("/market-signal-provider-configs", h.CreateMarketProviderConfig)
	g.PUT("/market-signal-provider-configs/:id", h.UpdateMarketProviderConfig)
	g.POST("/market-signal-provider-configs/:id/health-check", h.HealthCheckMarketProvider)
	g.POST("/market-signal-provider-configs/:id/:action", h.SetMarketProviderEnabled)
	g.POST("/performance/import", h.ImportPerformance)
	g.POST("/imports/performance/preview", h.PreviewPerformanceCSV)
	g.POST("/imports/performance/confirm", h.ConfirmPerformanceCSV)
	g.GET("/performance", h.ListPerformance)
	g.GET("/performance/summary", h.PerformanceSummary)
	g.GET("/evaluation/selection-performance", h.SelectionPerformance)
	g.GET("/calibration/report", h.CalibrationReport)
	g.GET("/selection-configs", h.ListSelectionConfigs)
	g.POST("/selection-configs", h.CreateSelectionConfig)
	g.POST("/selection-configs/:id/review", h.ReviewSelectionConfig)
	g.POST("/selection-configs/:id/activate", h.ActivateSelectionConfig)
	g.GET("/candidates/:id/analysis", h.LatestAnalysis)
	g.GET("/candidates/:id/analyses", h.ListAnalyses)
	g.POST("/candidates/:id/approve", h.ApproveCandidate)
	g.POST("/candidates/:id/reject", h.RejectCandidate)
	g.POST("/candidates/:id/watch", h.WatchCandidate)
	g.GET("/catalog-products", h.ListCatalog)
	g.GET("/catalog-products/:id", h.GetCatalog)
	g.POST("/catalog-products/:id/listing-drafts", h.CreateListingDraft)
	g.POST("/listing-content/bulk-generate", h.BulkGenerateListingContent)
	g.POST("/publish-packages/bulk-generate", h.BulkGeneratePublishPackages)
	g.POST("/listing-operation-batches", h.CreateListingOperationBatch)
	g.GET("/listing-operation-batches", h.ListListingOperationBatches)
	g.GET("/listing-operation-batches/:id", h.GetListingOperationBatch)
	g.GET("/listing-operation-batches/:id/items", h.ListListingOperationBatchItems)
	g.POST("/listing-operation-batches/:id/retry-failed", h.RetryFailedListingOperationBatch)
	g.POST("/listing-operation-batches/:id/cancel", h.CancelListingOperationBatch)
	g.GET("/listing-drafts", h.ListListingDrafts)
	g.GET("/listing-drafts/:id", h.GetListingDraft)
	g.GET("/listing-drafts/:id/workspace", h.GetListingWorkspace)
	g.GET("/listing-drafts/:id/sell-test-readiness", h.GetSellTestReadiness)
	g.GET("/listing-drafts/:id/content-versions", h.ListListingContentVersions)
	g.POST("/listing-drafts/:id/content/restore", h.RestoreListingContent)
	g.PUT("/listing-drafts/:id/assets", h.UpdateListingAssets)
	g.POST("/listing-drafts/:id/assets/upload", h.UploadListingAsset)
	g.DELETE("/listing-drafts/:id/assets/:assetId", h.DeleteListingAsset)
	g.GET("/listing-assets/:id/file", h.ViewListingAsset)
	g.POST("/listing-drafts/:id/content/generate", h.GenerateListingContent)
	g.PUT("/listing-drafts/:id/content", h.UpdateListingContent)
	g.POST("/listing-drafts/:id/content/review", h.ReviewListingContent)
	g.POST("/listing-drafts/:id/content-quality-reviews", h.CreateContentQualityReview)
	g.POST("/listing-drafts/:id/ready", h.MarkListingReady)
	g.POST("/listing-drafts/:id/publish-packages", h.GeneratePublishPackage)
	g.POST("/listing-drafts/:id/published-manual", h.MarkListingPublishedManual)
	g.GET("/publish-packages/:id/download", h.DownloadPublishPackage)
	g.PUT("/listing-drafts/:id", h.UpdateListingDraft)
	g.POST("/listing-drafts/:id/recalculate", h.RecalculateListingDraft)
	g.DELETE("/listing-drafts/:id", h.DeleteListingDraft)
	g.GET("/cost-center", h.CostCenter)
	g.GET("/selection-dashboard", h.SelectionDashboard)
	g.GET("/pricing-profiles", h.ListPricingProfiles)
	g.POST("/pricing-profiles", h.CreatePricingProfile)
	g.PUT("/pricing-profiles/:id", h.UpdatePricingProfile)
	g.POST("/pricing-profiles/:id/copy", h.CopyPricingProfile)
	g.POST("/pricing-profiles/:id/default", h.SetDefaultPricingProfile)
	g.DELETE("/pricing-profiles/:id", h.DeletePricingProfile)
}
